"""Write paper/lira_settings.tex from the experiment records.

Usage:  python tools/make_lira_settings.py results/lira_config.json

The JSON file must contain the settings that the LiRA-style evaluation actually
used (the same values that the evaluation script read), for example:
    {"n_member": <int>, "n_nonmember": <int>, "n_reference_models": <int>}
"""
import json, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main(path):
    cfg = json.loads(Path(path).read_text())
    vals = {}
    for key, macro in [("n_member", "LiRAnmem"), ("n_nonmember", "LiRAnnon"), ("n_reference_models", "LiRAK")]:
        v = cfg.get(key)
        if not isinstance(v, int) or isinstance(v, bool) or v <= 0:
            sys.exit(f"'{key}' must be a positive integer in {path}, got {v!r}")
        vals[macro] = v
    if vals["LiRAK"] < 2:
        sys.exit("A likelihood-ratio attack needs at least two reference models (in/out).")
    lines = ["% Generated by tools/make_lira_settings.py from " + str(path)]
    lines += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in vals.items()]
    (ROOT / "paper" / "lira_settings.tex").write_text("\n".join(lines) + "\n")
    print("wrote paper/lira_settings.tex:", vals)


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
